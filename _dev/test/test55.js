// انبار، ثبت خروج: زبانه «تعویض روغن» فهرست سرویس دوره‌ای دستگاه را باز می‌کند؛ «چند قلم» با زبانه «مصرف» مصرف می‌ماند (روغن هم)
const {chromium}=require('playwright'); const http=require('http'), fs=require('fs'), path=require('path');
const HTML=fs.readFileSync(path.join(__dirname,'..','out.html'));
let fails=0; const ok=(c,m)=>{ console.log((c?'  ok  ':'  FAIL ')+m); if(!c) fails++; };
const sleep=ms=>new Promise(r=>setTimeout(r,ms));
(async()=>{
  const web=http.createServer((q,r)=>{ r.writeHead(200,{'Content-Type':'text/html; charset=utf-8'}); r.end(HTML); }); await new Promise(r=>web.listen(0,r));
  const br=await chromium.launch({executablePath:process.env.CHROMIUM||undefined});
  const c=await br.newContext({locale:'fa-IR',viewport:{width:1100,height:900}});
  const p=await c.newPage(); const errs=[]; p.on('pageerror',e=>{ if(!/Unexpected token '<'/.test(String(e))) errs.push(String(e)); });
  const boot=async()=>{ await p.waitForFunction(()=>window.ntQr,null,{timeout:15000});
    await p.addStyleTag({content:'.sydlg:not(#ntQrDlg),.sybd{display:none!important}'}); await p.evaluate(()=>{ window.ntLocked=false; document.body.classList.remove('ntlocked'); try{ ntBoot(); }catch(e){} }); await sleep(800);
    await p.evaluate(()=>window.postMessage({nt:'go',tab:'انبار'},'*')); await sleep(1500);
    for(const x of p.frames()){ if(x===p.mainFrame()) continue; try{ if(await x.evaluate(()=>!!document.getElementById('oTypeSeg'))) return x; }catch(e){} } };
  await p.goto(`http://localhost:${web.address().port}/nt/s.html`); let f=await boot();
  ok(!!f,'بخش انبار باز شد');
  await f.click('#oNew'); await sleep(200);
  await f.fill('#oDev','بیل مکانیکی کوماتسو PC290'); await f.evaluate(()=>document.getElementById('oDev').dispatchEvent(new Event('input',{bubbles:true}))); await sleep(200);
  await f.click('#oTypeSeg [data-t="svc"]'); await sleep(300);
  const st=await f.evaluate(()=>({alt:!document.getElementById('altNet').hidden, box:document.getElementById('netBox').style.display, n:document.querySelectorAll('#netList .nsvc').length, title:document.getElementById('netTitle').textContent}));
  ok(st.alt,'زبانه «تعویض روغن»: بخش سرویس دوره‌ای خودکار باز شد');
  ok(st.box!=='none' && st.n>0 && /PC290/.test(st.title),'سرویس‌های همان دستگاه آمد ('+st.n+' سرویس)');
  await f.click('#oTypeSeg [data-t="msr"]'); await sleep(150);
  ok(await f.evaluate(()=>document.getElementById('altNet').hidden),'زبانه «مصرف»: بخش سرویس دوره‌ای بسته شد');
  await f.click('.alts [data-alt="altMulti"]'); await sleep(150);
  await f.fill('#oMulti','روغن هیدرولیک، 20'); await f.click('#oMultiAdd'); await sleep(300);
  let r=await f.evaluate(()=>{ const x=outRows[outRows.length-1]; return x?{svc:x.svc,rep:x.rep,item:x.item,q:x.qty}:null; });
  ok(r && r.svc===0 && r.q===20,'«چند قلم» با زبانه «مصرف»: روغن هیدرولیک ۲۰ لیتر → مصرف ('+JSON.stringify(r)+')');
  await f.evaluate(()=>{ try{ save(); }catch(e){} }); await sleep(300);
  await p.reload(); f=await boot(); await sleep(300);
  r=await f.evaluate(()=>{ const x=outRows.filter(o=>/هیدرولیک/.test(o.item||'') && +o.qty===20).pop(); return x?{svc:x.svc}:null; });
  ok(r && !r.svc,'بعد از باز کردن دوباره هم «مصرف» ماند (به تعویض روغن نرفت)');
  await f.click('#oNew'); await sleep(150); await f.click('#oTypeSeg [data-t="svc"]'); await sleep(150);
  await f.click('.alts [data-alt="altMulti"]'); await sleep(150);
  await f.fill('#oDev','لودر ZL50'); await f.fill('#oMulti','فیلتر روغن، 1'); await f.click('#oMultiAdd'); await sleep(300);
  r=await f.evaluate(()=>{ const x=outRows[outRows.length-1]; return x?{svc:x.svc}:null; });
  ok(r && r.svc===1,'«چند قلم» با زبانه «تعویض روغن» → تعویض روغن');
  ok(errs.length===0,'بدون خطا '+errs.join('|'));
  console.log(fails?fails+' شکست':'همه موفق'); await br.close(); web.close(); process.exit(fails?1:0);
})();
