// عکس‌ها: ثبت، گروه‌بندی بخش/قطعه، ارسال با برچسب، حذف، امنیت
const {chromium}=require('playwright'); const http=require('http'), fs=require('fs'), path=require('path');
const HTML=fs.readFileSync(path.join(__dirname,'..','out.html'));
let fails=0; const ok=(c,m)=>{ console.log((c?'  ok  ':'  FAIL ')+m); if(!c) fails++; };
const sleep=ms=>new Promise(r=>setTimeout(r,ms));
(async()=>{
  const web=http.createServer((q,r)=>{ r.writeHead(200,{'Content-Type':'text/html; charset=utf-8'}); r.end(HTML); }); await new Promise(r=>web.listen(0,r));
  const br=await chromium.launch({executablePath:process.env.CHROMIUM||undefined});
  const c=await br.newContext({locale:'fa-IR',viewport:{width:390,height:844}}); const p=await c.newPage(); const errs=[];
  p.on('pageerror',e=>errs.push(String(e)));
  await p.goto(`http://localhost:${web.address().port}/nt/s.html`); await p.waitForFunction(()=>window.ntSync&&window.ntNav,null,{timeout:15000});
  await p.addStyleTag({content:'.sydlg,.sybd{display:none!important}'});
  await p.evaluate(()=>{ window.ntLocked=false; document.body.classList.remove('ntlocked'); try{ ntBoot(); }catch(e){} });
  const IDX=await p.evaluate(()=>DOCS.findIndex(d=>d.name==='عکس‌ها'));
  ok(IDX>=0,'زبانه «عکس‌ها» هست');
  await p.evaluate(i=>show(i),IDX); await sleep(1800);
  const F=(fn,a)=>p.evaluate(([fn,a,i])=>{ const w=frames[i].contentWindow, d=frames[i].contentDocument; return (new Function('d','w','a','return ('+fn+')(d,w,a)'))(d,w,a); },[fn,a,IDX]);
  const FA=(fn,a)=>p.evaluate(async([fn,a,i])=>{ const w=frames[i].contentWindow, d=frames[i].contentDocument; return await (new Function('d','w','a','return ('+fn+')(d,w,a)'))(d,w,a); },[fn,a,IDX]);
  const addPhotos=async(n,dev,sec,part)=>{
    await FA(`async(d,w,a)=>{ const mk=k=>new Promise(r=>{ const c=w.document.createElement('canvas'); c.width=1600; c.height=1200; const x=c.getContext('2d'); x.fillStyle='hsl('+(k*70)+',60%,50%)'; x.fillRect(0,0,1600,1200); x.fillStyle='#fff'; x.font='80px sans-serif'; x.fillText('عکس '+k,200,300); c.toBlob(b=>r(new w.File([b],'a'+k+'.jpg',{type:'image/jpeg'})),'image/jpeg'); });
      const dt=new w.DataTransfer(); for(let k=0;k<a.n;k++) dt.items.add(await mk(k+1)); const i=d.getElementById('fIn'); i.files=dt.files; i.dispatchEvent(new w.Event('change')); }`,{n});
    await sleep(500);
    await F(`(d,w,a)=>{ d.getElementById('fDev').value=a.dev; [...d.querySelectorAll('#secs [data-s]')].find(b=>b.dataset.s===a.sec)?.click(); d.getElementById('fPart').value=a.part; d.getElementById('fSave').click(); }`,{dev,sec,part});
    await sleep(2500);
  };
  ok(await F('(d)=>d.getElementById("fCam").getAttribute("capture")==="environment"&&!!d.getElementById("pCam")'),'دکمه «دوربین» مستقیم دوربین را باز می‌کند');
  console.log('1) ثبت');
  await addPhotos(2,'کامیون TRS02','سیستم باد','پمپ باد');
  let m=await p.evaluate(()=>JSON.parse(localStorage.nt_photos_v1||'[]'));
  ok(m.length===2 && m[0].dev==='کامیون TRS02' && m[0].sec==='سیستم باد' && m[0].part==='پمپ باد' && /^\d{4}\/\d{2}\/\d{2}$/.test(m[0].date),'دو عکس با دستگاه، بخش، قطعه و تاریخ ذخیره شد');
  ok(await F('(d)=>d.querySelectorAll(".grid img").length')===2,'دو تصویر کوچک دیده می‌شود');
  ok(/پمپ باد/.test(await F('(d)=>d.getElementById("main").innerText')),'عنوان قطعه «پمپ باد»');
  const sz=await FA(`async(d,w)=>{ const db=await new Promise(r=>{ const q=w.indexedDB.open('ntphotos'); q.onsuccess=()=>r(q.result); }); const b=await new Promise(r=>{ const q=db.transaction('full').objectStore('full').getAll(); q.onsuccess=()=>r(q.result); }); return b.map(x=>x.size); }`);
  ok(sz.length===2 && sz.every(s=>s>1000 && s<400000),'عکس کوچک‌شده در حافظه گوشی است '+JSON.stringify(sz));
  console.log('2) بخش‌ها');
  await addPhotos(1,'کامیون TRS02','برقی','استارتر');
  const chips=await F('(d)=>[...d.querySelectorAll("#main .chips .cp")].map(b=>b.dataset.sec)');
  ok(chips.includes('برقی')&&chips.includes('سیستم باد'),'چیپ بخش‌ها: '+chips.join('،'));
  await F('(d)=>d.querySelector("#main [data-sec=\\"برقی\\"]").click()');
  ok(await F('(d)=>d.querySelectorAll(".grid img").length')===1,'فیلتر بخش «برقی»: یک عکس');
  await F('(d)=>d.querySelector("#main [data-sec=\\"\\"]").click()');
  console.log('3) ارسال');
  await F('(d)=>d.querySelector(".th").click()'); await sleep(500);
  ok(await F('(d)=>d.getElementById("vw").classList.contains("on")'),'نمایش بزرگ باز شد');
  await F(`(d,w)=>{ w.navigator.canShare=()=>true; w.navigator.share=async x=>{ w.__s={t:x.text,n:x.files.map(f=>f.type+'|'+f.name)}; }; d.getElementById('vSend').click(); }`); await sleep(800);
  const sh=await F('(d,w)=>w.__s'); ok(sh&&/#کامیون_TRS02/.test(sh.t)&&/#/.test(sh.t)&&sh.n[0].startsWith('image/jpeg'),'ارسال با برچسب: '+JSON.stringify(sh).slice(0,150));
  console.log('4) حذف');
  await F('(d)=>d.getElementById("vDel").click()'); ok((await p.evaluate(()=>JSON.parse(localStorage.nt_photos_v1).length))===3,'ضربه اول حذف نمی‌کند');
  await F('(d)=>d.getElementById("vDel").click()'); await sleep(500);
  ok((await p.evaluate(()=>JSON.parse(localStorage.nt_photos_v1).length))===2,'ضربه دوم حذف کرد');
  console.log('4b) برگشت و حالت مشاهده');
  await F('(d)=>d.getElementById("vClose").click()');
  await F('(d)=>d.getElementById("back").click()'); await sleep(300);
  await F('(d)=>d.querySelector("[data-dev]").click()'); await sleep(300);
  ok(await F('(d)=>!!d.getElementById("back")'),'دوباره وارد صفحه دستگاه شد');
  await p.evaluate(i=>{ frames[i].contentWindow.history.back(); },IDX); await sleep(500);
  ok(await F('(d)=>!!d.querySelector("[data-dev]")&&!d.getElementById("back")'),'دکمه برگشت گوشی به فهرست دستگاه‌ها می‌برد');
  ok(await F('(d)=>!d.getElementById("pCam").hidden'),'«عکس تازه» همیشه هست (حالت مشاهده هم)');
  console.log('4c) پشتیبان');
  await p.evaluate(()=>{ const a=JSON.parse(localStorage.nt_photos_v1); a.forEach(x=>x.ts=Date.now()-9*864e5); localStorage.nt_photos_v1=JSON.stringify(a); });
  await p.evaluate(()=>show(0)); await sleep(1500);
  ok(/۲ عکس پشتیبان ندارد/.test(await p.evaluate(()=>frames[0].contentDocument.getElementById('atCard').innerText)),'«امروز»: عکس بیش از یک هفته بدون پشتیبان');
  await p.evaluate(i=>show(i),IDX); await sleep(1200);
  ok(/عکس پشتیبان ندارد/.test(await F('(d)=>d.getElementById("main").innerText')),'کارت «پشتیبان ندارد» دیده می‌شود');
  await F(`(d,w)=>{ w.navigator.canShare=()=>true; w.navigator.share=async x=>{ w.__bk=(w.__bk||0)+x.files.length; w.__bkt=x.text; }; d.getElementById('bkGo').click(); }`); await sleep(1200);
  ok(await F('(d,w)=>w.__bk')===2 && /پشتیبان عکس‌ها/.test(await F('(d,w)=>w.__bkt')),'همه عکس‌های بدون پشتیبان فرستاده شد');
  ok((await p.evaluate(()=>JSON.parse(localStorage.nt_photos_v1).filter(x=>x.bk).length))===2,'عکس‌ها «پشتیبان دارد» شدند');
  ok(/همه عکس‌ها پشتیبان دارند/.test(await F('(d)=>d.getElementById("main").innerText')),'کارت: همه پشتیبان دارند');
  await F('(d)=>d.getElementById("bkAgain").click()'); await sleep(1000);
  ok(await F('(d,w)=>w.__bk')===4,'«ارسال دوباره» همان عکس‌ها را برای برنامه دیگر فرستاد');
  await p.evaluate(()=>show(0)); await sleep(1500);
  ok(!/پشتیبان ندارد/.test(await p.evaluate(()=>frames[0].contentDocument.getElementById('atCard').innerText.replace(/پشتیبان ندارید/g,''))),'بعد از پشتیبان، یادآور «امروز» رفت');
  await p.evaluate(i=>show(i),IDX); await sleep(1200);
  console.log('5) عکس گوشی دیگر + امنیت');
  await p.evaluate(()=>{ const a=JSON.parse(localStorage.nt_photos_v1); a.push({id:'zz1',dev:'<img src=x onerror=window.__x=1>',sec:'"><b>x</b>',part:'<script>window.__y=1<\/script>',note:'',date:'1405/07/19',by:'',ts:1}); localStorage.nt_photos_v1=JSON.stringify(a); });
  await p.evaluate(()=>show(0)); await sleep(500); await p.evaluate(i=>show(i),IDX); await sleep(1200);
  await F('(d)=>d.getElementById("back")&&d.getElementById("back").click()');
  ok(await F('(d,w)=>!w.__x&&!w.__y&&!d.querySelector("#main img[src=x],#main script")'),'متن خطرناک اجرا نشد');
  ok(await F('(d)=>!!d.querySelector("[data-dev]")'),'فهرست دستگاه‌ها هست');
  await F('(d)=>[...d.querySelectorAll("[data-dev]")].find(b=>/onerror/.test(b.dataset.dev)).click()'); await sleep(600);
  await F('(d)=>d.querySelector(".th").click()'); await sleep(500);
  ok(/روی گوشی دیگری/.test(await F('(d)=>d.getElementById("vIm").innerText')),'عکسِ گوشی دیگر: پیام روشن');
  ok(errs.length===0,'بدون خطا '+errs.join('|'));
  console.log(fails?fails+' شکست':'همه موفق'); await br.close(); web.close(); process.exit(fails?1:0);
})();
