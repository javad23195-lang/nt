// امروز: یادداشت لغوشده (لغو شد / به فردا / حذف کامل)
const {chromium}=require('playwright'); const http=require('http'), fs=require('fs'), path=require('path');
const HTML=fs.readFileSync(path.join(__dirname,'..','out.html'));
let fails=0; const ok=(c,m)=>{ console.log((c?'  ok  ':'  FAIL ')+m); if(!c) fails++; };
const sleep=ms=>new Promise(r=>setTimeout(r,ms));
(async()=>{
  const web=http.createServer((q,r)=>{ r.writeHead(200,{'Content-Type':'text/html; charset=utf-8'}); r.end(HTML); }); await new Promise(r=>web.listen(0,r));
  const br=await chromium.launch({executablePath:process.env.CHROMIUM||undefined});
  const c=await br.newContext({locale:'fa-IR',viewport:{width:420,height:900}}); const p=await c.newPage(); const errs=[];
  p.on('pageerror',e=>errs.push(String(e)));
  await p.goto(`http://localhost:${web.address().port}/nt/s.html`); await p.waitForFunction(()=>window.ntSync&&window.ntNav,null,{timeout:15000});
  await p.addStyleTag({content:'.sydlg,.sybd{display:none!important}'});
  await p.evaluate(()=>{ window.ntLocked=false; document.body.classList.remove('ntlocked'); try{ ntBoot(); }catch(e){} });
  const IDX=await p.evaluate(()=>DOCS.findIndex(d=>d.name==='امروز'));
  await p.evaluate(i=>show(i),IDX); await sleep(1500);
  const fr=(await (await p.$$('iframe'))[IDX].contentFrame());
  const add=async v=>{ await fr.evaluate(v=>{ const e=document.getElementById('tIn'); e.value=v; document.getElementById('tAdd').click(); },v); await sleep(150); };
  const T=()=>p.evaluate(()=>JSON.parse(localStorage.nt_today_todo_v1||'[]'));
  const row=txt=>fr.evaluate(t=>{ const r=[...document.querySelectorAll('#tList .td')].find(x=>x.innerText.includes(t)); return r?{cls:r.className,t:r.innerText}:null; },txt);
  const clickIn=(txt,sel)=>fr.evaluate(([t,s])=>{ const r=[...document.querySelectorAll('#tList .td')].find(x=>x.innerText.includes(t)); r.querySelector(s).click(); },[txt,sel]);
  await add('یادداشت الف'); await add('یادداشت ب'); await add('یادداشت ج');
  console.log('1) ✕ → گزینه‌ها');
  await clickIn('یادداشت الف','.x'); await sleep(150);
  let R=await row('یادداشت الف'); ok(R && /act/.test(R.cls) && /لغو شد/.test(R.t) && /به فردا/.test(R.t) && /حذف کامل/.test(R.t) && /بازگشت/.test(R.t),'چهار گزینه نمایش داده شد');
  ok((await T()).length===3,'با ✕ چیزی پاک نشد');
  await clickIn('یادداشت الف','.ta-b'); await sleep(150); ok(!/act/.test((await row('یادداشت الف')).cls),'«بازگشت» کار می‌کند');
  console.log('2) لغو شد');
  await clickIn('یادداشت الف','.x'); await sleep(100); await clickIn('یادداشت الف','.ta-c'); await sleep(200);
  let A=(await T()).find(x=>x.t==='یادداشت الف'); ok(A && A.done && A.cx===1 && A.doneAt,'ذخیره: done + cx');
  R=await row('یادداشت الف'); ok(R && /cxl/.test(R.cls) && /لغو شد/.test(R.t),'در فهرست: خط‌خورده با «لغو شد»');
  await p.screenshot({path:'/tmp/claude-0/td.png'});
  await fr.evaluate(()=>{ const r=[...document.querySelectorAll('#tList .td')].find(x=>x.innerText.includes('یادداشت الف')); const cb=r.querySelector('.ck'); cb.checked=false; cb.dispatchEvent(new Event('change',{bubbles:true})); }); await sleep(200);
  A=(await T()).find(x=>x.t==='یادداشت الف'); ok(A && !A.done && !A.cx,'برداشتن تیک: دوباره باز شد');
  console.log('3) به فردا');
  await clickIn('یادداشت ب','.x'); await sleep(100); await clickIn('یادداشت ب','.ta-t'); await sleep(200);
  const B=(await T()).find(x=>x.t==='یادداشت ب'), K=await fr.evaluate(()=>K);
  ok(B && B.date>K && !B.done,'تاریخ به فردا رفت ('+(B&&B.date)+')');
  ok(!(await row('یادداشت ب')),'از فهرست امروز رفت');
  console.log('4) حذف کامل (دو بار)');
  await clickIn('یادداشت ج','.x'); await sleep(100); await clickIn('یادداشت ج','.ta-d'); await sleep(100);
  ok((await T()).some(x=>x.t==='یادداشت ج'),'یک بار زدن: پاک نشد');
  await clickIn('یادداشت ج','.ta-d'); await sleep(200);
  ok(!(await T()).some(x=>x.t==='یادداشت ج'),'دو بار زدن: پاک شد');
  console.log('5) امنیت');
  await add('<img src=x onerror=window.__x=1>'); await clickIn('img src','.x').catch(()=>{}); await sleep(200);
  ok(await fr.evaluate(()=>!window.__x && !document.querySelector('#tList img')),'متن خطرناک اجرا نشد');
  ok(errs.length===0,'بدون خطا '+errs.join('|'));
  console.log(fails?fails+' شکست':'همه موفق'); await br.close(); web.close(); process.exit(fails?1:0);
})();
